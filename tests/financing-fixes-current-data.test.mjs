import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { sha256, validateReviewedFilesFixture } from '../scripts/qa/build-reviewed-delta.mjs';
import { buildFundingIndex, loadFundingIndexSources } from '../scripts/lib/funding-index.mjs';
import { countedCapital } from '../src/lib/funding-capital.mjs';

// Intentionally no historical reader import: every assertion uses actual data.
const lock = JSON.parse(readFileSync(new URL('./fixtures/financing-fixes-reviewed-revision-20261125.json', import.meta.url), 'utf8'));
const baseline = JSON.parse(readFileSync(new URL('./fixtures/financing-fixes-merged-baseline-20261125.json', import.meta.url), 'utf8'));
const delta = validateReviewedFilesFixture(JSON.parse(readFileSync(new URL('./fixtures/financing-fixes-20261125.json', import.meta.url), 'utf8')));

test('all captured real financing files match the independently supplied final data revision', () => {
  assert.deepEqual(Object.keys(lock).sort(), ['baselineSha', 'candidateSha', 'files', 'version']);
  assert.equal(lock.version, 1);
  assert.equal(lock.baselineSha, 'b3b901831da6ed7e50cd0dee15d636e4cdbbe4fc');
  assert.match(lock.candidateSha, /^[a-f0-9]{40}$/);
  assert.deepEqual(Object.keys(lock.files).sort(), Object.keys(baseline.files).sort());
  const changedPaths = Object.keys(lock.files).filter(file => lock.files[file] !== baseline.files[file]);
  assert.deepEqual(delta.files.map(entry => entry.path).sort(), changedPaths.sort(), 'No missing changed file or unused exemption');
  for (const [file, digest] of Object.entries(lock.files)) {
    assert.match(digest, /^[a-f0-9]{64}$/);
    assert.equal(sha256(readFileSync(new URL('../' + file, import.meta.url))), digest, file + ': actual final source/generated bytes');
    const entry = delta.files.find(entry => entry.path === file);
    if (entry) {
      assert.equal(entry.beforeSha256, baseline.files[file]);
      assert.equal(entry.afterSha256, digest);
    }
  }
});

test('the unprojected current funding payload retains canonical builder and real capital-accounting parity', async () => {
  const sources = await loadFundingIndexSources(new URL('../data/funding-index/', import.meta.url).pathname);
  const built = buildFundingIndex(sources);
  const current = JSON.parse(readFileSync(new URL('../src/data/funding-index.json', import.meta.url), 'utf8'));
  assert.deepEqual(current.companies.map(company => Object.fromEntries(Object.entries(company).filter(([key]) => key !== 'logo'))), built.companies);
  for (const key of ['rounds', 'milestones', 'investors', 'portfolioDisclosures', 'reportedTotals']) {
    assert.deepEqual(current[key], built[key], key);
  }
  assert.equal(current.summary.selectedCompanies, built.companies.length);
  assert.equal(current.summary.indexedRounds, built.rounds.length);
  assert.equal(current.summary.regulatoryMilestones, built.milestones.length);
  assert.equal(current.summary.observedCapitalUsdM, Number(built.rounds.reduce((sum, round) => sum + countedCapital(round), 0).toFixed(2)));
});
